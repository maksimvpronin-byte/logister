export function apiError(message: string | undefined, status: number): Error & { status: number } {
  const text = message && (errors[message] ?? (/[А-Яа-яЁё]/.test(message) ? message : undefined));
  const fallback = status === 401 ? "Войдите, чтобы продолжить." : status === 403 ? "Недостаточно прав для этого действия." : status === 409 ? "Данные уже изменились. Обновите страницу и повторите действие." : status === 400 || status === 422 ? "Проверьте введённые данные и повторите действие." : `Не удалось выполнить запрос (HTTP ${status}). Повторите попытку.`;
  return Object.assign(new Error(text || fallback), { status });
}

export function streamDisplayTitle(stream: { name: string; title: string }): string {
  return stream.name === "all" && ["All messages", "Unmatched messages", "Все сообщения"].includes(stream.title)
    ? "Сообщения без совпавших правил" : stream.title;
}
